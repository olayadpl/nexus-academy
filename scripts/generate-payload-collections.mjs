import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(process.cwd(), 'src', 'features')

function walk(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  let files = []
  for (const entry of entries) {
    const res = path.resolve(dir, entry.name)
    if (entry.isDirectory()) files = files.concat(walk(res))
    else files.push(res)
  }
  return files
}

const allFiles = walk(root)
const collectionFiles = allFiles.filter((f) => f.endsWith('.collection.ts'))

const outPath = path.resolve(process.cwd(), 'src', 'payload-collections.generated.ts')

const imports = []
const refs = []

collectionFiles.forEach((file, idx) => {
  const rel = './' + path.relative(path.resolve(process.cwd(), 'src'), file).replace(/\\/g, '/')
  const name = `Collection${idx}`
  imports.push(`import { ${guessExportName(file)} as ${name} } from '${rel}'`)
  refs.push(name)
})

const content = `// This file is auto-generated by scripts/generate-payload-collections.mjs\n` +
  imports.join('\n') + '\n\n' +
  `export const featureCollections = [${refs.join(', ')}]\n`

fs.writeFileSync(outPath, content, 'utf8')
console.log('Wrote', outPath)

function guessExportName(file) {
  const base = path.basename(file).replace(/\.collection\.ts$/, '')
  return `${capitalize(camel(base))}Collection`
}

function camel(str) {
  return str.split(/[-_\.]/).map((s, i) => i === 0 ? s.toLowerCase() : capitalize(s)).join('')
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1)
}
